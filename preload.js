const{contextBridge,ipcRenderer}=require("electron");
contextBridge.exposeInMainWorld("electronAPI",{
sendAppData:(data)=>ipcRenderer.send("block-app",data),
receiveApps:(callback)=>ipcRenderer.on("apps-found",(_event,apps)=>callback(apps)),
receiveBlockerStatus:(callback)=>ipcRenderer.on("blocker-status",(_event,message)=>callback(message)),
receiveBlockerError:(callback)=>ipcRenderer.on("blocker-error",(_event,message)=>callback(message)),
receiveBlockerEnded:(callback)=>ipcRenderer.on("blocker-ended",(_event,message)=>callback(message)),
receiveSchedules:(callback)=>ipcRenderer.on("schedules-loaded",(_event,schedules)=>callback(schedules)),
requestSchedules:()=>ipcRenderer.send("load-schedules")
});